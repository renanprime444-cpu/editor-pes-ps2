static uint32_t rd32(const uint8_t *p){ return (uint32_t)p[0]|((uint32_t)p[1]<<8)|((uint32_t)p[2]<<16)|((uint32_t)p[3]<<24); }
static void wr32(uint8_t *p, uint32_t v){ p[0]=(uint8_t)v; p[1]=(uint8_t)(v>>8); p[2]=(uint8_t)(v>>16); p[3]=(uint8_t)(v>>24); }

static void crypt_block(uint8_t *b, int start, int size, int enc){
    int j = 0;
    for (int off = start; off + 4 <= start + size; off += 4){
        uint32_t w = rd32(b + off), x;
        if (enc) x = ((w ^ CCONST) - CCONST) + KEY[j];
        else     x = ((w - KEY[j]) + CCONST) ^ CCONST;
        wr32(b + off, x);
        j = (j + 1) % 446;
    }
}

int opt_open(Opt *o, uint8_t *buf, size_t len){
    memset(o, 0, sizeof(*o));
    if (len == LEN_WE10){
        o->we10 = 1; o->B = WB; o->S = WS;
        o->player_base = 37140; o->edit_base = 14312;
        o->names_off = 750596; o->n_names = 138;
        o->squad_off = 657932 + 9778; o->n_squad = 146;
    } else if (len == LEN_PES6){
        o->we10 = 0; o->B = P6B; o->S = P6S;
        o->player_base = 37164; o->edit_base = 14336;
        o->names_off = 751472; o->n_names = 140;
        o->squad_off = 657956 + 9774; o->n_squad = 140;
    } else return -1;
    o->buf = buf; o->len = len;
    for (int b = 0; b < NBLOCKS; b++)
        if (rd32(buf + o->B[b] - 12) == (uint32_t)o->S[b]) o->hdr_ok++;
    for (int b = 1; b < NBLOCKS; b++) crypt_block(buf, o->B[b], o->S[b], 0);
    return 0;
}

void opt_seal(const Opt *o, uint8_t *out){
    memcpy(out, o->buf, o->len);
    for (int b = 1; b < NBLOCKS; b++) crypt_block(out, o->B[b], o->S[b], 1);
    for (int b = 0; b < NBLOCKS; b++){
        uint32_t s = 0;
        for (int off = o->B[b]; off + 4 <= o->B[b] + o->S[b]; off += 4) s += rd32(out + off);
        wr32(out + o->B[b] - 8, s);
    }
}

int player_valid(const Opt *o, int id){
    (void)o;
    return (id >= 0 && id < 5000) || (id >= 32768 && id < 32768 + 183);
}

static int player_pos(const Opt *o, int id, int off){
    int p;
    if (!player_valid(o, id)) return -1;
    if (id >= 32768) p = o->edit_base + (id - 32768) * 124 + off;
    else             p = o->player_base + id * 124 + off;
    if (p < 1 || (size_t)p >= o->len) return -1;
    return p;
}

int stat_get(const Opt *o, int id, int off, int shift, int mask){
    int p = player_pos(o, id, off);
    if (p < 0) return -1;
    return ((((int)o->buf[p] << 8) | o->buf[p-1]) >> shift) & mask;
}

int stat_set(Opt *o, int id, int off, int shift, int mask, int val){
    int p = player_pos(o, id, off);
    if (p < 0) return -1;
    int cur = ((int)o->buf[p] << 8) | o->buf[p-1];
    cur &= 65535 & ~(mask << shift);
    cur |= (val & mask) << shift;
    o->buf[p-1] = (uint8_t)(cur & 255);
    o->buf[p]   = (uint8_t)((cur >> 8) & 255);
    return 0;
}

int ability_get(const Opt *o, int id, int idx){
    if (idx < 0 || idx >= N_ABILITIES) return -1;
    return stat_get(o, id, ABILITIES[idx].off, ABILITIES[idx].shift, ABILITIES[idx].mask);
}

int ability_set(Opt *o, int id, int idx, int val){
    if (idx < 0 || idx >= N_ABILITIES) return -1;
    if (val < 0) val = 0;
    if (val > 127) val = 127;
    if (stat_set(o, id, ABILITIES[idx].off, ABILITIES[idx].shift, ABILITIES[idx].mask, val) < 0) return -1;
    return stat_set(o, id, ABILITY_EDITED.off, ABILITY_EDITED.shift, ABILITY_EDITED.mask, 1);
}

const char *club_name(const Opt *o, int club, char *tmp, int tmpsz){
    if (club < 0 || club >= o->n_names){ tmp[0] = 0; return tmp; }
    const uint8_t *p = o->buf + o->names_off + club * 88;
    int i = 0;
    while (i < tmpsz - 1 && i < 60 && p[i] >= 32 && p[i] < 127){ tmp[i] = (char)p[i]; i++; }
    tmp[i] = 0;
    return tmp;
}

int squad_id(const Opt *o, int club, int slot){
    if (club < 0 || club >= o->n_squad || slot < 0 || slot >= 32) return -1;
    const uint8_t *p = o->buf + o->squad_off + club * 64 + slot * 2;
    int id = p[0] | (p[1] << 8);
    if (id == 0 || id == 0xFFFF) return -1;
    return id;
}
